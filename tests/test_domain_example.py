"""Run the public domain SDK journey against real business and runtime SQLite stores."""

import sqlite3
from contextlib import closing

import pytest
from examples.domain_harness.demo import DemoHost, run


@pytest.mark.asyncio
async def test_domain_example_commits_replays_and_validates_a_second_domain(tmp_path):
    result = await run(tmp_path)
    assert result["committed"] == {"revision": 2, "revenue_usd": 120}
    assert result["replayed"] is True
    assert result["invoice_decision"] == "balanced"
    assert result["regression_pass_rate"] == 1
    assert result["default_inference_route"] == "deliberate"


# Generated by the ship coverage audit.
# Value: protects=the demo's atomic revision and idempotency receipt contracts;
# fails_when=a stale or conflicting write changes business rows or receipts;
# why_new=the existing journey covers successful commit and runtime replay only; seam=none.
@pytest.mark.parametrize("conflict", ["stale_revision", "receipt_reuse"])
def test_domain_example_rejects_conflicting_writes_without_mutating_state(tmp_path, conflict):
    database = tmp_path / "business.db"
    host = DemoHost(database)
    committed = host.apply(1, 120, "original-key")
    with closing(sqlite3.connect(database)) as db:
        before_deals = db.execute("SELECT * FROM deals ORDER BY id").fetchall()
        before_receipts = db.execute("SELECT * FROM receipts ORDER BY key").fetchall()

    if conflict == "stale_revision":
        with pytest.raises(ValueError, match="stale deal revision"):
            host.apply(1, 900, "new-key")
    else:
        with pytest.raises(ValueError, match="idempotency key reused"):
            host.apply(1, 900, "original-key")

    with closing(sqlite3.connect(database)) as db:
        assert db.execute("SELECT * FROM deals ORDER BY id").fetchall() == before_deals
        assert db.execute("SELECT * FROM receipts ORDER BY key").fetchall() == before_receipts
    assert host.apply(1, 120, "original-key") == committed
    assert host.current().revision == "2"
